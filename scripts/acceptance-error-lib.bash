#!/usr/bin/env bash
# Acceptance check (C16): in a clone of agentguru/error-lib, `asdf install` with this plugin and
# `make build` regenerate reasontype_string.go with no diff. Local only: needs gh access to the
# private repo and the golang plugin in your asdf. Runs in a throwaway asdf data dir, like a fresh
# machine: asdf installs Go there too. Your asdf data dir is not modified.

set -euo pipefail

plugin_dir="$(cd "$(dirname "$0")/.." && pwd)"
user_data_dir="${ASDF_DATA_DIR:-$HOME/.asdf}"
work="$(mktemp -d "${TMPDIR:-/tmp}/asdf-stringer-acceptance.XXXXXX")"
trap 'chmod -R u+w "$work" 2>/dev/null; rm -rf "$work"' EXIT

export ASDF_DATA_DIR="$work/asdf-data"
# Plugins are copied, not symlinked: asdf does not list a symlinked plugin and would never reshim it.
mkdir -p "$ASDF_DATA_DIR/plugins/stringer"
cp -R "$plugin_dir/bin" "$plugin_dir/lib" "$ASDF_DATA_DIR/plugins/stringer/"
cp -R "$user_data_dir/plugins/golang" "$ASDF_DATA_DIR/plugins/golang"
export PATH="$ASDF_DATA_DIR/shims:$PATH"

gh repo clone agentguru/error-lib "$work/error-lib" -- -q --depth 1
cd "$work/error-lib"
grep -qx 'golang 1.25.5' .tool-versions
echo 'stringer 0.49.0' >>.tool-versions

asdf install
[ "$(command -v stringer)" = "$ASDF_DATA_DIR/shims/stringer" ]

rm reasontype_string.go
make build
test -f reasontype_string.go
git diff --exit-code -- reasontype_string.go
echo "acceptance: reasontype_string.go regenerated by stringer 0.49.0 with no diff"
